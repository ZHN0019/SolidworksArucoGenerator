        public static bool[,] GetMarker(int id)
        {
            if (id < 0 || id >= Markers.Length)
                throw new ArgumentOutOfRangeException(nameof(id), "Marker ID must be in the range 0..30.");

            var result = new bool[GridSize, GridSize];
            for (int row = 0; row < GridSize; row++)
            {
                for (int column = 0; column < GridSize; column++)
                    result[row, column] = Markers[id][row][column] == '1';
            }

            return result;
        }
